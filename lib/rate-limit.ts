/*
 * Small in-memory fixed-window limiter. Each server instance counts on its
 * own, so on serverless hosts it slows guessing rather than strictly capping
 * it — enough for low-value lookups. Use a shared store (e.g. Redis) for
 * anything stricter.
 */
const buckets = new Map<string, { count: number; resetAt: number }>();

export function rateLimit(key: string, limit: number, windowMs: number): boolean {
  const now = Date.now();
  if (buckets.size > 10_000) {
    for (const [k, b] of buckets) if (b.resetAt <= now) buckets.delete(k);
  }
  const bucket = buckets.get(key);
  if (!bucket || bucket.resetAt <= now) {
    buckets.set(key, { count: 1, resetAt: now + windowMs });
    return true;
  }
  bucket.count += 1;
  return bucket.count <= limit;
}
